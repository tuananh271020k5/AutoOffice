export type HostKind = 'word' | 'excel' | 'powerpoint';

export interface HostContext {
  kind: HostKind;
  displayName: string;
}

export interface DocumentIdentity {
  /** Unique ID for this specific Office Task Pane window (stored in sessionStorage) */
  windowSessionId: string;
  /** Composite key identifying the current window + document project */
  documentKey: string;
  /** Human-readable label for the current document/project (e.g. "HopDong.docx" or "Phiên #A1B2") */
  documentLabel: string;
}

const WINDOW_SESSION_STORAGE_KEY = 'autooffice_window_session_id';
const WINDOW_ACTIVE_CONV_STORAGE_KEY = 'autooffice_window_active_conv_id';

export class UnsupportedHostError extends Error {
  constructor(actual: string) {
    super(`AutoOffice does not support this Office host: ${actual}`);
    this.name = 'UnsupportedHostError';
  }
}

export function detectHost(): HostContext {
  if (typeof Office === 'undefined' || !Office.context || !Office.context.host) {
    // Dev mode (vite preview, no Office). Default to Word so the existing
    // Word-only dev experience keeps working when you visit the URL directly.
    return { kind: 'word', displayName: 'Word' };
  }
  switch (Office.context.host) {
    case Office.HostType.Word:
      return { kind: 'word', displayName: 'Word' };
    case Office.HostType.Excel:
      return { kind: 'excel', displayName: 'Excel' };
    case Office.HostType.PowerPoint:
      return { kind: 'powerpoint', displayName: 'PowerPoint' };
    default:
      throw new UnsupportedHostError(String(Office.context.host));
  }
}

function getOrCreateWindowSessionId(): string {
  try {
    if (typeof sessionStorage !== 'undefined') {
      let existing = sessionStorage.getItem(WINDOW_SESSION_STORAGE_KEY);
      if (!existing) {
        existing = (typeof crypto !== 'undefined' && crypto.randomUUID)
          ? crypto.randomUUID().slice(0, 8)
          : Math.random().toString(36).slice(2, 10);
        sessionStorage.setItem(WINDOW_SESSION_STORAGE_KEY, existing);
      }
      return existing;
    }
  } catch {
    // Ignore storage errors in restricted environments
  }
  return 'default';
}

function extractFileName(rawUrl: string): string {
  try {
    const decoded = decodeURIComponent(rawUrl);
    const parts = decoded.split(/[\\/]/);
    const last = (parts[parts.length - 1] || '').trim();
    // Ignore temporary sideloaded document names generated by office-addin-debugging
    if (/^Word add-in [0-9a-f-]{8,}/i.test(last)) {
      return '';
    }
    return last;
  } catch {
    return '';
  }
}

/**
 * Returns the isolated identity for the current Office window and document.
 * Each Word/Excel/PowerPoint window has its own `sessionStorage`, guaranteeing
 * that opening multiple Word windows simultaneously never collides on the same chat.
 */
export function getDocumentIdentity(): DocumentIdentity {
  const windowSessionId = getOrCreateWindowSessionId();
  let rawUrl = '';
  try {
    if (typeof Office !== 'undefined' && Office.context?.document?.url) {
      rawUrl = String(Office.context.document.url).trim();
    }
  } catch {
    rawUrl = '';
  }

  const fileName = rawUrl ? extractFileName(rawUrl) : '';
  const shortWin = windowSessionId.slice(0, 4).toUpperCase();
  const documentLabel = fileName || `Phiên #${shortWin}`;
  const documentKey = fileName
    ? `win:${windowSessionId}::file:${fileName.toLowerCase()}`
    : `win:${windowSessionId}`;

  return {
    windowSessionId,
    documentKey,
    documentLabel,
  };
}

/**
 * Gets the active conversation ID bound strictly to THIS window's sessionStorage.
 * Ensures a newly opened Word window always starts a fresh conversation instead of
 * inheriting a closed or other window's conversation.
 */
export function getWindowActiveConversationId(): string | null {
  try {
    if (typeof sessionStorage !== 'undefined') {
      return sessionStorage.getItem(WINDOW_ACTIVE_CONV_STORAGE_KEY);
    }
  } catch {
    // Ignore
  }
  return null;
}

export function setWindowActiveConversationId(conversationId: string | null): void {
  try {
    if (typeof sessionStorage !== 'undefined') {
      if (conversationId) {
        sessionStorage.setItem(WINDOW_ACTIVE_CONV_STORAGE_KEY, conversationId);
      } else {
        sessionStorage.removeItem(WINDOW_ACTIVE_CONV_STORAGE_KEY);
      }
    }
  } catch {
    // Ignore
  }
}
